CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(10)  NOT NULL DEFAULT 'USER',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'))
);
CREATE UNIQUE INDEX uq_users_email_lower ON users (lower(email));

CREATE TABLE categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    slug       VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_categories_name UNIQUE (name),
    CONSTRAINT uq_categories_slug UNIQUE (slug)
);

CREATE TABLE recipes (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id            BIGINT        NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    category_id          BIGINT        NOT NULL REFERENCES categories (id) ON DELETE RESTRICT,
    title                VARCHAR(150)  NOT NULL,
    description          VARCHAR(2000),
    image_url            VARCHAR(2048),
    cooking_time_minutes INTEGER       NOT NULL,
    servings             INTEGER       NOT NULL,
    created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_recipes_time CHECK (cooking_time_minutes > 0),
    CONSTRAINT ck_recipes_servings CHECK (servings > 0)
);
CREATE INDEX idx_recipes_category ON recipes (category_id);
CREATE INDEX idx_recipes_author ON recipes (author_id);
CREATE INDEX idx_recipes_created_at ON recipes (created_at DESC);
CREATE INDEX idx_recipes_title_trgm ON recipes USING gin (lower(title) gin_trgm_ops);

CREATE TABLE ingredients (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id  BIGINT       NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    name       VARCHAR(100) NOT NULL,
    quantity   VARCHAR(50)  NOT NULL,
    unit       VARCHAR(30),
    sort_order INTEGER      NOT NULL
);
CREATE INDEX idx_ingredients_recipe ON ingredients (recipe_id);
CREATE INDEX idx_ingredients_name_trgm ON ingredients USING gin (lower(name) gin_trgm_ops);

CREATE TABLE instructions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id   BIGINT        NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    step_number INTEGER       NOT NULL,
    description VARCHAR(2000) NOT NULL,
    CONSTRAINT ck_instructions_step CHECK (step_number > 0),
    -- DEFERRABLE: PUT mengganti seluruh langkah, baris baru boleh masuk sebelum baris lama dihapus
    CONSTRAINT uq_instructions_step UNIQUE (recipe_id, step_number) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE favorites (
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    recipe_id  BIGINT      NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, recipe_id)
);
CREATE INDEX idx_favorites_recipe ON favorites (recipe_id);
CREATE INDEX idx_favorites_user_created ON favorites (user_id, created_at DESC);

CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash)
);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);
