-- Kontrak v2.4.0: komentar, ulasan, artikel. Foto hasil upload disimpan di disk, bukan di database.

CREATE TABLE comments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id  BIGINT        NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    -- satu tingkat balasan; menghapus komentar utama ikut menghapus balasannya
    parent_id  BIGINT        REFERENCES comments (id) ON DELETE CASCADE,
    author_id  BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    content    VARCHAR(1000) NOT NULL,
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_comments_recipe_top ON comments (recipe_id, created_at DESC) WHERE parent_id IS NULL;
CREATE INDEX idx_comments_parent ON comments (parent_id);

CREATE TABLE reviews (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id  BIGINT       NOT NULL REFERENCES recipes (id) ON DELETE CASCADE,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    rating     INTEGER      NOT NULL,
    content    VARCHAR(500),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT uq_reviews_recipe_user UNIQUE (recipe_id, user_id)
);
CREATE INDEX idx_reviews_recipe_created ON reviews (recipe_id, created_at DESC);
CREATE INDEX idx_reviews_featured ON reviews (created_at DESC) WHERE rating >= 4 AND content IS NOT NULL;

CREATE TABLE articles (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id            BIGINT        NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    title                VARCHAR(150)  NOT NULL,
    excerpt              VARCHAR(300),
    content              VARCHAR(20000) NOT NULL,
    cover_image_url      VARCHAR(2048),
    category             VARCHAR(10)   NOT NULL,
    reading_time_minutes INTEGER       NOT NULL,
    published_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_articles_category CHECK (category IN ('TIPS', 'CERITA', 'BAHAN', 'TEKNIK')),
    CONSTRAINT ck_articles_reading_time CHECK (reading_time_minutes > 0)
);
CREATE INDEX idx_articles_published ON articles (published_at DESC, id DESC);
CREATE INDEX idx_articles_category ON articles (category);

CREATE TABLE article_tags (
    article_id BIGINT      NOT NULL REFERENCES articles (id) ON DELETE CASCADE,
    sort_order INTEGER     NOT NULL,
    tag        VARCHAR(30) NOT NULL,
    PRIMARY KEY (article_id, sort_order),
    -- DEFERRABLE: PUT bisa menukar urutan tag dalam satu transaksi
    CONSTRAINT uq_article_tags_tag UNIQUE (article_id, tag) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX idx_article_tags_tag ON article_tags (tag);
